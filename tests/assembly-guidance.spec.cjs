const {test,expect}=require('@playwright/test');

test('confirmed step quantities remain separate from the whole hardware kit',async({page})=>{
  await page.goto('./#step/base');
  const screws=page.locator('.part-chip[data-part-dialog="Ф4"]');
  await expect(screws).toContainText('× 2');
  await expect(page.locator('.part-chip[data-part-dialog="19"]')).toContainText('× 1');
  await expect(page.locator('.part-chip[data-part-dialog="Ф10"]')).toContainText('× 2');
  await expect(page.locator('.diagram-card [data-scene] [data-part="19"]')).toHaveCount(3);
  await expect(screws).not.toContainText('× 52');
  await screws.click();
  await expect(page.locator('.part-measurements')).toContainText('52 шт.');
  await page.keyboard.press('Escape');
  await page.locator('.diagram-inspector [data-select-part="19"]').click();
  await expect(page.locator('.selected-part-count')).toContainText('2 шт.');
  await expect(page.locator('.selected-part-step')).toContainText('Передний цоколь — 1 шт.');
  await page.goto('./#step/sides');
  await expect(page.locator('.part-chip[data-part-dialog="Ф4"]')).toContainText('× 3');
  await expect(page.locator('.diagram-card [data-scene] [data-part="19"]')).toHaveCount(3);
  await expect(page.locator('.part-chip[data-part-dialog="Ф10"]')).toContainText('× 2');
  await expect(page.locator('.part-chip[data-part-dialog="1"],.diagram-card [data-part="1"],.diagram-inspector [data-select-part="1"]')).toHaveCount(0);
  await expect(page.locator('.diagram-card [data-part="2"]').first()).toBeVisible();
  await page.goto('./#step/partitions');
  await expect(page.locator('.part-chip[data-part-dialog="Ф4"]')).toContainText('× 5');
  await expect(page.locator('.part-chip[data-part-dialog="Ф10"]')).toContainText('× 2');
  await expect(page.locator('.part-chip[data-part-dialog="19"]')).toContainText('× 1');
  await expect(page.locator('.part-chip[data-part-dialog="Ф8"]')).toContainText('× 2');
  await expect(page.locator('.diagram-card [data-part="1"],.diagram-inspector [data-select-part="1"]')).toHaveCount(0);
  await expect(page.locator('.diagram-card [data-scene] [data-part="19"]')).toHaveCount(6);
  await expect(page.locator('.diagram-card [data-scene] [data-part="19"].is-current')).toHaveCount(3);
  await page.locator('.diagram-inspector [data-select-part="19"]').click();
  await expect(page.locator('.selected-part-step')).toContainText('Задний цоколь — 1 шт.');
  await expect(page.locator('.hidden-plinth-outline path')).toHaveAttribute('fill','none');
  await expect(page.locator('.hidden-plinth-outline')).toHaveClass(/is-selected/);
  expect(await page.locator('.hidden-plinth-outline path').evaluate(el=>getComputedStyle(el).fill)).toBe('none');
  const dividerActions=await page.locator('.step-instructions li').allTextContents();
  const tightenDivider=dividerActions.findIndex(text=>text.includes('Оба винта затяните вручную до плотного стыка'));
  const prepareLowerDivider=dividerActions.findIndex(text=>text.includes('Не затягивайте низ №18 окончательно'));
  const installRear=dividerActions.findIndex(text=>text.includes('возьмите отложенный задний цоколь'));
  expect(tightenDivider).toBeGreaterThanOrEqual(0);
  expect(installRear).toBeGreaterThan(tightenDivider);
  expect(installRear).toBeGreaterThan(prepareLowerDivider);
  await page.goto('./#step/remaining');
  await expect(page.locator('.part-chip[data-part-dialog="Ф4"]')).not.toContainText('× 52');
  await page.goto('./#step/main-shelves');
  await expect(page.locator('.part-chip[data-part-dialog="Ф4"]')).toContainText('× 18');
  await expect(page.locator('.part-chip[data-part-dialog="Ф10"]')).toContainText('× 2');
  await expect(page.locator('.diagram-inspector [data-select-part="1"]')).toBeVisible();
  await expect(page.locator('.diagram-card [data-part="1"][role="button"]')).toBeVisible();
  await expect(page.locator('.diagram-result')).toContainText('№1 установлена после обеих полок №17');
  await expect(page.locator('.part-chip[data-part-dialog="Ф8"]')).toContainText('× 6');
  await expect(page.locator('.part-chip[data-part-dialog="Ф9"]')).toContainText('× 6');
  // Prepare the underside before it becomes inaccessible; keep divider screws reachable until fastened.
  await expect(page.locator('.step-instructions li').first()).toContainText('штока Ф8 в готовые отверстия снизу полки №10');
  const actions=await page.locator('.step-instructions li').allTextContents();
  const prepareLower=actions.findIndex(text=>text.includes('штока Ф8 в готовые отверстия снизу полки №10'));
  const installWide=actions.findIndex(text=>text.includes('установите широкие полки №9 и №10'));
  const fastenWide=actions.findIndex(text=>text.includes('затяните крепления №9/10'));
  const prepareLeft=actions.findIndex(text=>text.includes('Теперь найдите 2 узкие полки №17'));
  const fitLeft=actions.findIndex(text=>text.includes('надвиньте их на подготовленные штоки и шканты'));
  const installSide=actions.findIndex(text=>text.includes('приставьте левую боковину №1'));
  expect(installWide).toBeGreaterThan(prepareLower);
  expect(fastenWide).toBeGreaterThanOrEqual(installWide);
  expect(prepareLeft).toBeGreaterThan(fastenWide);
  expect(fitLeft).toBeGreaterThan(prepareLeft);
  expect(installSide).toBeGreaterThan(fitLeft);
  await expect(page.locator('.safety-note')).toContainText('отсоедините ВСЕ имеющиеся соединения №1');
  await expect(page.locator('.safety-note')).toContainText('не снимайте боковину по этому короткому порядку');
  await page.locator('.diagram-zoom').click();
  await expect(page.locator('#zoom-dialog .zoom-result')).toBeVisible();
  await expect(page.locator('#zoom-dialog .zoom-result')).toContainText('№1 установлена после обеих полок №17');
  await page.keyboard.press('Escape');
  await page.locator('[data-joint="confirmat"]').click();
  await expect(page.locator('#zoom-dialog .zoom-result')).toHaveCount(0);
  await page.keyboard.press('Escape');
  await expect(page.locator('.part-chip[data-part-dialog="Ф8"]')).toContainText('внутренних торцов №17');
  await page.locator('.part-chip[data-part-dialog="17"]').click();
  await expect(page.locator('#help-dialog')).toContainText('Полка2');
  await expect(page.locator('#help-dialog')).toContainText('Круглые эксцентриковые посадки обращены к высокой стойке №3');
  await expect(page.locator('#help-dialog')).toContainText('двумя конфирматами');
});

test('connection explanations open separately and remain large on a phone',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  for(const [step,type]of [['base','confirmat'],['base','glide'],['partitions','cam-dowel']]){
    await page.goto(`./#step/${step}`);
    const button=page.locator(`[data-joint="${type}"]`);
    await button.click();
    await expect(page.locator('#zoom-content > svg')).toHaveCount(1);
    await expect(page.locator('#zoom-dialog .diagram-inspector')).toHaveCount(0);
    expect(await page.locator('#zoom-content > svg').evaluate(svg=>getComputedStyle(svg).maxHeight)).toBe('none');
    expect((await page.locator('#zoom-content > svg').boundingBox()).height).toBeGreaterThan(type==='glide'?150:700);
    await page.keyboard.press('Escape');
    await expect(button).toBeFocused();
  }
  await page.setViewportSize({width:320,height:844});
  await page.goto('./#step/main-shelves');
  await page.locator('.diagram-zoom').click();
  const result=page.locator('#zoom-dialog .zoom-result');
  await expect(result).toBeInViewport();
  expect(await result.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBeTruthy();
  const size=await result.evaluate(el=>getComputedStyle(el).fontSize);
  await page.locator('[data-action="zoom-in"]').click();
  expect(await result.evaluate(el=>getComputedStyle(el).fontSize)).toBe(size);
  await page.keyboard.press('Escape');
  await page.goto('./#step/base');
  await page.locator('.diagram-zoom').click();
  await expect(page.locator('#zoom-dialog .zoom-result')).toHaveCount(0);
});
